    }

    /** Ensure DR sum equals CR sum (within tiny tolerance) */
    protected function assertBalanced(array $lines, float $tol = 0.0001): void
    {
        $dr = 0.0; $cr = 0.0;
        foreach ($lines as $l) {
            $amt = (float)$l['Amount'];
            if ($l['DRCR'] === 'DR') $dr += $amt;
            if ($l['DRCR'] === 'CR') $cr += $amt;
        }
        if (abs($dr - $cr) > $tol) {
            throw new Exception("Unbalanced posting: DR={$dr} != CR={$cr}");
        }
    }

