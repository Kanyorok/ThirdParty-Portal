            'Amount'            => 'required|numeric|min:0.0000001',
            'TaxAmount'         => 'nullable|numeric|min:0',
            'BranchID'          => 'nullable|integer|exists:t_Branches,Id',
            'DepartmentID'      => 'nullable|integer|exists:t_Departments,Id',
            'CurrencyID'        => 'nullable|integer|exists:t_Currencies,Id',
            'CurrencyCode'      => 'nullable|string|max:10',
            'TransactionType'      => 'nullable|string|max:200',
            'ExchangeRate'      => 'nullable|numeric|min:0',
            'Narration'         => 'nullable|string|max:255',
            'SourceTable'       => 'nullable|string|max:100',
            'SystemDescription' => 'nullable|string|max:150',
            'IdempotencyKey'    => 'nullable|string|max:100',
