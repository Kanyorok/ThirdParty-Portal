            'ThirdPartyID'=> 'nullable|integer',
            '*.ReferenceNumber'   => 'required|string|max:100',
            '*.TransactionType'   => 'required|string|max:100',
            '*.TransactionTypeID'   => 'nullable|string|max:100',
            '*.ModuleID'          => 'nullable',//|integer', // FK not enforced here; already validated in payload
            '*.SourceTable'       => 'nullable|string|max:100',
            '*.GLAccountID'       => 'required|integer|exists:t_FinanceGLAccounts,Id',
            '*.BranchID'          => 'nullable|integer|exists:t_Branches,Id',
            '*.DepartmentID'      => 'nullable|integer|exists:t_Departments,Id',
            '*.DRCR'              => 'required|in:DR,CR',
            '*.Amount'            => 'required|numeric|min:0.0000001',
            '*.CurrencyID'        => 'nullable|integer|exists:t_Currencies,Id',
            '*.CurrencyCode'      => 'required|string|max:10',
            '*.ExchangeRate'      => 'required|numeric|min:0',
            '*.Narration'         => 'nullable|string|max:255',
            '*.BatchNumber'       => 'nullable|string|max:50',
            '*.IsTaxable'         => 'boolean',
            '*.IsReversal'        => 'nullable|boolean',
            '*.ReversedTransactionID' => 'nullable|integer|exists:'.$this->txTable.',Id',
            '*.SystemDescription' => 'nullable|string|max:150',
