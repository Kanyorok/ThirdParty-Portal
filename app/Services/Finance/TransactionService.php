    protected function resolveTypeMapping($moduleId, $transactionTypeId): FinanceGLMapping
    {
        $m = FinanceGLMapping::where('ModuleID', $moduleId)
            ->where('TransactionTypeID', $transactionTypeId)
            ->first();

        if (!$m) {
            throw new Exception("No active GL mapping for ModuleID {$moduleId}, TransactionTypeID {$transactionTypeId}.");
        }

        return $m;
    }

    /** Add audit fields and batch number */
    protected function ensureAuditAndBatch(array $lines, string $batch): array
    {
        $now = Carbon::now();
        $uid = Auth::id() ?? 0;

        return array_map(function ($l) use ($batch, $now, $uid) {
            $l['BatchNumber'] = $l['BatchNumber'] ?? $batch;
            $l['CreatedBy']   = $l['CreatedBy']   ?? $uid;
            $l['ModifiedBy']  = $l['ModifiedBy']  ?? $uid;
            $l['CreatedOn']   = $l['CreatedOn']   ?? $now;
            $l['ModifiedOn']  = $l['ModifiedOn']  ?? $now;
            return $l;
        }, $lines);
    }

    /** Persist lines atomically */

    protected function persist(array $lines, array $options): array
    {
        if (empty($lines)) {
            throw new \InvalidArgumentException('No lines to post.');
        }

        $batch = $options['batch'] ?? null;
        $ids   = [];

        DB::transaction(function () use ($lines, $batch, &$ids) {
            foreach ($lines as $line) {
                // Ensure Amount sign convention: DR -> negative, CR -> positive
                $isDebit = array_key_exists('IsDebit', $line)
                    ? (bool)$line['IsDebit']
                    : (($line['DRCR'] ?? null) === 'DR');
                $amt = abs((float)($line['Amount'] ?? 0));
                $storageLine = $line;
                $storageLine['Amount'] = $isDebit ? -$amt : $amt;

                // 1) insert one line, get its ID
                $trxId = DB::table($this->txTable)->insertGetId($storageLine);
                $ids[] = $trxId;

                // 2) update balances for that line (use abs amount internally)
                $this->updateBalanceForLine($trxId, $storageLine);
            }

            // 3) audit
            if (function_exists('activity')) {
                activity('Transaction Posting')
                    ->causedBy(Auth::id())
                    ->withProperties(['batch' => $batch, 'lines' => count($lines)])
                    ->log("Posted batch {$batch}");
            }
        });

        return [
            'status'          => 'success',
            'transactionIds'  => $ids,       // all inserted IDs
            'batchNumber'     => $batch,
            'count'           => count($lines),
        ];
    }

    /** Batch helpers
     * @throws RandomException
     */
    protected function generateBatchNumber(): string
    {
        return 'B' . Carbon::now()->format('YmdHis') . random_int(100, 999);
    }

    /**
     * @throws RandomException
     */
    protected function generateReversalBatchNumber(): string
    {
        return 'RB' . Carbon::now()->format('YmdHis') . random_int(100, 999);
    }

    /**
     * Create a Journal and its lines
     */
    public function createJournal(array $header, array $lines): array
    {
        // ---------- Idempotency ----------
        $jKey = $header['IdempotencyKey']
            ?? ('JRN:' . ($header['ReferenceNumber'] ?? 'REF') . ':' . ($header['BatchNumber'] ?? 'NB'));

        // If you store journals with an IdempotencyKey column, check that first.
        // If not, we’ll check by (Date, Description, BatchNumber) pattern as a fallback:
        $existing = FinanceJournalEntry::query()
            ->when(isset($header['IdempotencyKey']), fn($q) => $q->where('IdempotencyKey', $jKey))
            ->when(!isset($header['IdempotencyKey']), function ($q) use ($header) {
                $q->whereDate('Date', $header['Date'] ?? now()->toDateString())
                    ->where('Description', $header['Description'] ?? '')
                    ->when(!empty($header['BatchNumber']), fn($qq) => $qq->where('BatchNumber', $header['BatchNumber']));
            })
            ->first();

        if ($existing) {
            return ['status' => 'exists', 'journal_id' => $existing->Id, 'message' => 'Journal already exists (idempotent).'];
        }

        // ---------- Validate header ----------
        $hv = Validator::make($header, [
            'Date'            => 'required|date',
            'Description'     => 'nullable|string|max:255',
            'ReferenceNumber' => 'nullable|string|max:100',
            'BatchNumber'     => 'nullable|string|max:50',
            'IdempotencyKey'  => 'nullable|string|max:100',
        ]);
        if ($hv->fails()) {
            throw new \Exception('Journal header validation failed: ' . json_encode($hv->errors()->toArray()));
        }

        // ---------- Normalize + validate lines ----------
        if (empty($lines) || !is_array($lines[0] ?? null)) {
            throw new \Exception('Journal lines are required.');
        }

        // Normalize DR/CR -> IsDebit, Debit, Credit
        $norm = [];
        $totalDebit = 0.0; $totalCredit = 0.0;

        foreach ($lines as $i => $l) {
            $lv = Validator::make($l, [
                'GLAccountID'  => 'required|integer|exists:t_FinanceGLAccounts,Id',
                'BranchID'     => 'nullable|integer|exists:t_Branches,Id',
                'DepartmentID' => 'nullable|integer|exists:t_Departments,Id',
                'Amount'       => 'required|numeric|min:0.0000001',
                'DRCR'         => 'nullable|in:DR,CR',
                'IsDebit'      => 'nullable|boolean',
                'Narration'    => 'nullable|string|max:255',
            ]);
            if ($lv->fails()) {
                throw new \Exception("Journal line #".($i+1)." validation failed: " . json_encode($lv->errors()->toArray()));
            }

            $amount = (float)$l['Amount'];
            $isDebit = array_key_exists('IsDebit', $l)
                ? (bool)$l['IsDebit']
                : (($l['DRCR'] ?? null) === 'DR');

            $debit  = $isDebit ? $amount : 0.0;
            $credit = $isDebit ? 0.0 : $amount;

            $totalDebit  += $debit;
            $totalCredit += $credit;

            $norm[] = [
                'GLAccountID'  => (int)$l['GLAccountID'],
                'BranchID'     => $l['BranchID'] ?? null,
                'DepartmentID' => $l['DepartmentID'] ?? null,
                'IsDebit'      => $isDebit,
                'Amount' => $isDebit ? $amount * -1 : $amount,
                'Debit' => $debit * -1,
                'Credit'       => $credit,
                'Narration'    => $l['Narration'] ?? null,
            ];
        }

        if (round($totalDebit - $totalCredit, 6) !== 0.0) {
            throw new \Exception("Journal not balanced. DR={$totalDebit}, CR={$totalCredit}");
        }

        // ---------- Persist (single transaction) ----------
        return DB::transaction(function () use ($header, $norm, $totalDebit, $totalCredit, $jKey) {
            $uid = Auth::id() ?? 0;
            $now = Carbon::now();

            /** @var \App\Models\Finance\FinanceJournalEntry $journal */
            $journal = FinanceJournalEntry::create([
                'Date'           => $header['Date'],
                'Type'=> $header['IsScheduled']?'recurring':'normal',
                'SourceModule'   => $payload['ModuleID'] ?? '1100000', // Default to Finance module if not specified
                'Description'    => $header['Description'] ?? null,
                'SystemDescription'=>$header['Description'] ?? null,
                'Reference'      => $header['ReferenceNumber'] ?? null, // if your table has a Reference column
                'BatchNumber'    => $header['BatchNumber'] ?? null,     // add column if you want linkage
                'IdempotencyKey' => $jKey ?? null,                      // add column if you decide to store it
                'TotalDebit' => $totalDebit * -1 ?? null,                // optional summary cols if present
                'TotalCredit'    => $totalCredit ?? null,
                'CurrencyID'     => $header['CurrencyID'] ?? null,
                'ApprovalStatus'=>'posted',
                'ApprovalReason'=>'System Generated Approval.',
                'CreatedBy'      => 1,
                'ModifiedBy'     => 1,
                'CreatedOn'      => $now,
                'ModifiedOn'     => $now,
            ]);

            //Post rucurring Journal if so
            if($header['IsScheduled']){
                $voucher=FinanceVoucher::find($header['VoucherID']);
                RecurrentJournal::create([
                    'JournalEntryId'=> $journal->Id,
                    'StartDate'      => $voucher->StartDate,
                    'CuttOffDate'    =>  $voucher->StartDate,
                    'Frequency'      => CodeDetail::where('CodeID','JournalPaymentFrequency')
                                                ->where('Description',$voucher->Frequency)->value('Value'),
                    'ReferenceName'  => 'Voucher',
                    'Description'    => $voucher->Description,
                    'SystemDescription'=>'Auto Voucher Processing: '.$voucher->VoucherNo,
                    'CreatedBy'      =>1,
                    'ModifiedBy'     => 1,
                ]);
            }

            foreach ($norm as $ln) {
                FinanceJournalLines::create([
                    'JournalEntryId' => $journal->Id,
                    'GLAccountID'    => $ln['GLAccountID'],
                    'BranchID'       => $ln['BranchID'],
                    'DepartmentID'   => $ln['DepartmentID'],
                    'IsDebit'        => $ln['IsDebit'],
                    'Amount' => $ln['IsDebit'] ? $ln['Amount'] * -1 : $ln['Amount'],
                    'Debit' => $ln['Debit'] * -1,
                    'Credit'         => $ln['Credit'],
                    'Narration'      => $ln['Narration'],
                    'SystemDescription'      => $ln['Narration'],
                    'CreatedBy'      => 1,
                    'ModifiedBy'     => 1,
                ]);
            }

            if (function_exists('activity')) {
                activity('Journal Create')
                    ->performedOn($journal)
                    ->causedBy($uid)
                    ->withProperties(['lines' => count($norm)])
                    ->log('Created Journal '.$journal->Id);
            }

            return [
                'status'       => 'success',
                'journal_id'   => $journal->Id,
                'journal_ref'  =>$journal->RefNo,
                'lines_count'  => count($norm),
            ];
        });
    }

    protected function updateBalanceForLine(int $trxId, array $trx): void
    {
        $glAccountId = (int)$trx['GLAccountID'];
        $branchId    = $trx['BranchID'] ?? null;
        $amount = abs((float)$trx['Amount']);
        $drcr        = strtoupper($trx['DRCR'] ?? 'DR');     // DR or CR
        $rate        = (float)($trx['ExchangeRate'] ?? 1);
        $currencyId  = $trx['CurrencyID'] ?? null;

        // Sign: DR = -, CR = + (always start from absolute amount)
        $signed       = $drcr === 'DR' ? -$amount : $amount;

        // Base/ledger currency deltas (t_FinanceGLBranch stores all three)
        $localDelta   = $signed * $rate;   // base/ledger currency delta
        $foreignDelta = $currencyId ? $signed : 0;

        // Format to avoid float noise in SQL
        $fmt = fn($n) => number_format((float)$n, 5, '.', '');

        $uid = $trx['ModifiedBy'] ?? $trx['CreatedBy'] ?? (Auth::id() ?? 0);
        $now = now();

        // Grab GL meta (code + type). Prefer character "A/L/E/I/X" if available.
        $glMeta = DB::table('t_FinanceGLAccounts')
            ->select('GLCode', 'GLAccountTypeID')
            ->where('Id', $glAccountId)
            ->first();

        $glCode        = $trx['GLCode']        ?? ($glMeta->GLCode ?? '');
        $glAccountType = $trx['GLAccountTypeID'] ?? ($glMeta->GLAccountType ?? ($glMeta->GLAccountTypeID ?? null));

        // Does the (GLAccountID, BranchID) row exist?
        $exists = DB::table('t_FinanceGLBranch')
            ->where('GLAccountID', $glAccountId)
            ->when(is_null($branchId), fn($q) => $q->whereNull('BranchID'),
                fn($q) => $q->where('BranchID', $branchId))
            ->exists();

        if ($exists) {
            // UPDATE path → increment balances
            DB::table('t_FinanceGLBranch')
                ->when(true, function ($q) use ($glAccountId, $branchId) {
                    $q->where('GLAccountID', $glAccountId);
                    return is_null($branchId) ? $q->whereNull('BranchID') : $q->where('BranchID', $branchId);
                })
                ->update([
                    'LastTransactionId' => $trxId,
                    // increment with DB::raw – use base/ledger delta for Balance/LocalBalance
                    'Balance'           => DB::raw('Balance + '      . $fmt($localDelta)),
                    'LocalBalance'      => DB::raw('LocalBalance + ' . $fmt($localDelta)),
                    'ForeignBalance'    => DB::raw('ForeignBalance + ' . $fmt($foreignDelta)),
                    'ModifiedOn'        => $now,
                    'ModifiedBy'        => $uid,
                ]);

        } else {
            // INSERT path → set starting balances (no arithmetic here)
            DB::table('t_FinanceGLBranch')->insert([
                'GLAccountID'       => $glAccountId,
                'BranchID'          => $branchId,
                'GLCode'            => $glCode,
                'GLAccountType'     => (string)$glAccountType,
                'LastTransactionId' => $trxId,
                'IsActive'          => 1,
